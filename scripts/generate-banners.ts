import * as fs from 'node:fs';
import * as path from 'node:path';
import * as puppeteer from 'puppeteer';
import { chromeLaunchOptions, projectRoot } from './utils';

interface BaseImage {
  svg: (baseX: number, baseY: number, newWidth: number, newHeight: number) => string;
  width: number;
  height: number;
}

interface BannerImage {
  svgPath: `${string}.svg`;
  pngPath: `${string}.png`;
}

/**
 * 字标与标语。
 *
 * 字标必须与 manifest 的 productName 一致——Edge / Chrome 的商店页会把 manifest 名
 * 自动填进标题，图上的名字与之不符会让审核员以为装错了扩展。
 *
 * 字体栈不写单一字体名：本机没装 Ubuntu，Chrome 会退到默认 serif（Times），
 * 观感与界面里的无衬线完全对不上。列全后备，换机器渲染结果才稳定。
 */
const PRODUCT_NAME = 'CC for Web';
const TAGLINE = 'From Codeforces to your editor';
const FONT_FAMILY = "Ubuntu, 'Helvetica Neue', Helvetica, Arial, sans-serif";

/** 蓝色圆 + 白色十字的记号，两个方向共用。十字是镂空的，露出底色。 */
const iconMark = (cx: number, cy: number): string => `
  <g>
    <circle cx="${cx}" cy="${cy}" r="100" fill="var(--icon-color)" />
    <!--
      Horizontal bar width = circle radius
      Horizontal bar height = circle radius / 4
    -->
    <rect x="${cx - 50}" y="${cy - 12.5}" width="100" height="25" fill="var(--icon-inner-color)" />
    <rect x="${cx - 12.5}" y="${cy - 50}" width="25" height="100" fill="var(--icon-inner-color)" />
  </g>`;

// 宽扁画布（1400×560、1280×640、440×280 这类）用横排：图标在左，字标与标语在右
const horizontalBaseImage: BaseImage = {
  svg: (baseX, baseY, newWidth, newHeight) => `
<svg viewBox="0 0 790 200" x="${baseX}" y="${baseY}" width="${newWidth}" height="${newHeight}">
  <rect width="100%" height="100%" fill="var(--background-color)" />
  ${iconMark(100, 100)}
  <g font-family="${FONT_FAMILY}">
    <text x="240" y="93" fill="var(--text-color)" font-size="72px" font-weight="700">${PRODUCT_NAME}</text>
    <text x="242" y="147" fill="var(--text-dim-color)" font-size="30px">${TAGLINE}</text>
  </g>
</svg>
  `,
  width: 790,
  height: 200,
};

// 方画布（920×680 这类）用竖排：图标在上，字标与标语在下方居中
const verticalBaseImage: BaseImage = {
  svg: (baseX, baseY, newWidth, newHeight) => `
<svg viewBox="0 0 470 430" x="${baseX}" y="${baseY}" width="${newWidth}" height="${newHeight}">
  <rect width="100%" height="100%" fill="var(--background-color)" />
  ${iconMark(235, 115)}
  <g font-family="${FONT_FAMILY}" text-anchor="middle">
    <text x="235" y="312" fill="var(--text-color)" font-size="72px" font-weight="700">${PRODUCT_NAME}</text>
    <text x="235" y="366" fill="var(--text-dim-color)" font-size="30px">${TAGLINE}</text>
  </g>
</svg>
  `,
  width: 470,
  height: 430,
};

async function generateBanner(name: string, width: number, height: number): Promise<BannerImage> {
  const minMargin = Math.min(width, height) / 8;
  const availableWidth = width - minMargin * 2;
  const availableHeight = height - minMargin * 2;

  let bestImage: string = null;
  let bestTotalMargin: number = null;

  for (const baseImage of [horizontalBaseImage, verticalBaseImage]) {
    const baseRatio = Math.min(availableWidth / baseImage.width, availableHeight / baseImage.height);
    const newBaseWidth = baseImage.width * baseRatio;
    const newBaseHeight = baseImage.height * baseRatio;

    const baseX = (width - newBaseWidth) / 2;
    const baseY = (height - newBaseHeight) / 2;

    const totalMargin = baseX * 2 + baseY * 2;
    if (bestTotalMargin === null || totalMargin < bestTotalMargin) {
      bestImage = `
<!-- Generated by 'pnpm generate-banners', do not edit manually -->
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
  <style>
    :root {
      --background-color: #303030;
      --text-color: #ffffff;
      --text-dim-color: #b4b4b4;
      --icon-color: #0e639c;
      --icon-inner-color: var(--background-color);
    }
  </style>
  <rect width="100%" height="100%" fill="var(--background-color)" />
  ${baseImage.svg(baseX, baseY, newBaseWidth, newBaseHeight)}
</svg>
      `.trim();

      bestTotalMargin = totalMargin;
    }
  }

  const svgPath = path.resolve(projectRoot, `media/banners/${name}.svg`) as BannerImage['svgPath'];
  const pngPath = path.resolve(projectRoot, `media/banners/${name}.png`) as BannerImage['pngPath'];

  fs.writeFileSync(svgPath, bestImage.trim() + '\n');

  return { svgPath, pngPath };
}

const requiredBanners: [string, number, number][] = [
  ['github-social-preview', 1280, 640],
  ['chrome-small-promo', 440, 280],
  ['chrome-large-promo', 920, 680],
  ['chrome-marquee-promo', 1400, 560],
];

const browser = await puppeteer.launch(chromeLaunchOptions());

const page = await browser.newPage();

for (const [name, width, height] of requiredBanners) {
  console.log(`Generating banner ${name} of size ${width}x${height}`);

  const banner = await generateBanner(name, width, height);

  await page.goto(`file://${banner.svgPath}`);
  await page.setViewport({ width, height });
  await page.screenshot({ path: banner.pngPath });
}

await browser.close();
